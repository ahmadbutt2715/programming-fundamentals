// operators that we normally use in maths all are supported by C++ with same behaviour
/*
    +, -, *, /, %
*/

#include<iostream>
using namespace std;

int main(){
    int a = 10;
    int b = 2;
    cout << "a = " << a << endl << "b = " << b << endl << endl;

    cout << "a + b = " << a + b << endl;
    cout << "a - b = " << a - b << endl;
    cout << "a * b = " << a * b << endl;
    cout << "a / b = " << a / b << endl;
    cout << "a * b = " << a * b << endl;
    
    return 0;
}